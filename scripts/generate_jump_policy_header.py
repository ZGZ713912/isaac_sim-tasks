#!/usr/bin/env python3
"""Generate RMCS jump_policy.hpp from a selected export's deployment contract and gas table."""
from __future__ import annotations

import argparse
import hashlib
import json
import math
from pathlib import Path


def generate(contract: dict, gas_bytes: bytes) -> str:
    if hashlib.sha256(gas_bytes).hexdigest() != contract['gas_model_sha256']:
        raise ValueError('Gas table differs from the selected deployment contract')
    gas = json.loads(gas_bytes)
    control, request, command = (contract[k] for k in ('control', 'request', 'command'))
    if control['virtual_pair_overtravel_scope'] != 'jump-request':
        raise ValueError('Unsupported target-overtravel scope')
    tuck = control['tuck_spring_compensation']
    if tuck['mode'] != 'model':
        raise ValueError('This controller requires model-based tuck compensation')
    constants = {
        'ForwardLimit': command['forward_limit_m_s'], 'YawLimit': command['yaw_limit_rad_s'],
        'HeightMin': command['height_min_m'], 'HeightMax': command['height_max_m'],
        'HeightRate': command['height_rate_m_s'],
        'LegKp': control['leg_kp_nm_per_rad'], 'LegKd': control['leg_kd_nm_s_per_rad'],
        'Overtravel': control['virtual_pair_overtravel_rad'],
        'StandingHeight': request['standing_height_m'], 'CrouchHeight': request['crouch_height_m'],
        'ReleaseHeight': request['release_height_m'], 'CrouchSeconds': request['crouch_seconds'],
        'RequestDuration': request['outcome_seconds'] - request['nominal_request_delay_s'],
        'MinimumApex': request['apex_range_m'][0], 'MaximumApex': request['apex_range_m'][1],
        'MovingVxMax': request['moving_vx_max_m_s'],
        'MechanicalMin': contract['real_state_soft_limits_rad'][0],
        'MechanicalMax': contract['real_state_soft_limits_rad'][1],
        'LowCompressionRate': gas['force_extension']['low_compression_rate_per_m'],
        'HighCompressionSlope': gas['force_extension']['high_compression_slope_n_per_m'],
        'TuckGain': tuck['gain'], 'TuckCap': tuck['cap_nm'], 'ErrorOn': tuck['error_on_rad'],
        'ErrorFull': tuck['error_full_rad'], 'InwardPdFull': tuck['inward_pd_full_nm'],
    }
    if not all(isinstance(v, (int, float)) and not isinstance(v, bool) and math.isfinite(v)
               for v in constants.values()):
        raise ValueError('All control constants must be finite numbers')
    if not (constants['ReleaseHeight'] < constants['MinimumApex'] <= constants['MaximumApex']
            and constants['RequestDuration'] > 0 and constants['CrouchSeconds'] > 0
            and constants['ErrorFull'] > constants['ErrorOn'] and constants['InwardPdFull'] > 0
            and constants['ForwardLimit'] >= 0 and constants['YawLimit'] >= 0
            and constants['HeightMin'] <= constants['StandingHeight'] <= constants['HeightMax']
            and constants['HeightRate'] > 0 and constants['LegKp'] >= 0 and constants['LegKd'] >= 0
            and constants['Overtravel'] >= 0 and constants['MechanicalMin'] < constants['MechanicalMax']):
        raise ValueError('Invalid jump timing, apex range or tuck ramp')
    bounds = contract['winding_bounds_rad']
    if len(bounds) != 2 or any(len(side) != 2 or not side[0] < side[1] for side in bounds):
        raise ValueError('Expected two ordered winding bounds')

    def number(value):
        if not math.isfinite(value):
            raise ValueError('Non-finite gas/winding data')
        return format(value, '.17g')

    deployment_sha = contract['deployment_contract_sha256']
    if len(deployment_sha) != 64 or any(c not in '0123456789abcdef' for c in deployment_sha):
        raise ValueError('deployment_contract_sha256 must be a lowercase SHA-256')
    contract_sha = hashlib.sha256(json.dumps(contract, sort_keys=True, separators=(',', ':')).encode()).hexdigest()
    lines = ['#pragma once', '', '#include <array>', '#include <string_view>', '',
             '// Generated by the training repository scripts/generate_jump_policy_header.py.',
             f'// Source {contract["training_source_commit"]}; contract {contract_sha}.',
             '// Generation alone does not qualify a model for hardware deployment.',
             'namespace rmcs_core::controller::chassis::wheel_leg::jump_policy {',
             '// Must equal the wheelbipe_deployment_contract_sha256 metadata of the loaded ONNX.',
             f'inline constexpr std::string_view kDeploymentContractSha256 = "{deployment_sha}";',
             'struct GeometryKnot {',
             '    double delta_rad, compression_m, hip_length_jacobian, knee_length_jacobian;',
             '};', 'struct ForceKnot { double compression_m, force_n; };', '']
    for key, value in constants.items():
        lines.append(f'inline constexpr double k{key} = {number(value)};')
    rows = ','.join('{' + ','.join(map(number, side)) + '}' for side in bounds)
    lines.append('inline constexpr std::array<std::array<double, 2>, 2> kBounds{{' + rows + '}};')

    def table(name, kind, rows):
        if len(rows) < 2 or any(rows[i][0] >= rows[i+1][0] for i in range(len(rows)-1)):
            raise ValueError(f'{name} abscissae must be strictly increasing')
        lines.append(f'inline constexpr std::array<{kind}, {len(rows)}> k{name}' + '{{')
        lines.extend('    {' + ','.join(map(number, row)) + '},' for row in rows)
        lines.append('}};')

    table('Force', 'ForceKnot', list(zip(gas['compression_knots_m'], gas['force_knots_n'], strict=True)))
    for side, name in [('left', 'Left'), ('right', 'Right')]:
        row = gas['sides'][side]
        if [row['delta_rad'][0], row['delta_rad'][-1]] != bounds[0 if side == 'left' else 1]:
            raise ValueError('Winding bounds differ from gas geometry')
        rows = [(delta, compression, *jac) for delta, compression, jac in zip(
            row['delta_rad'], row['compression_m'], row['length_jacobian_m_per_rad'], strict=True)]
        if any(len(item) != 4 for item in rows):
            raise ValueError('Geometry requires two length Jacobians')
        table(name, 'GeometryKnot', rows)
    lines.append('} // namespace rmcs_core::controller::chassis::wheel_leg::jump_policy')
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--contract', type=Path, required=True, help='Selected export deployment contract JSON')
    parser.add_argument('--gas-model', type=Path, required=True, help='Gas model pinned by that contract')
    parser.add_argument('--output', type=Path, required=True, help='New header path; never overwrite')
    args = parser.parse_args()
    gas_bytes = args.gas_model.read_bytes()
    header = generate(json.loads(args.contract.read_text()), gas_bytes)
    with args.output.open('x') as stream:
        stream.write(header)
    print(args.output)


if __name__ == '__main__':
    main()
